package S1_Loops;

public class ForLoop2_printEvenNum_From2_to_10
{
    public static void main(String[] args) {

        //start num - 2
        //end num   -10
        //incr/decr -2

        //           4<=10      6
        for(int i=2; i<=10; i=i+2)
        {
            System.out.println(i);      //2 4
        }


    }
}
